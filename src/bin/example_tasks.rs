use std::time::Instant;

use numlin_v2::solver;
use numlin_v2::urls::decode_url;

#[allow(unused)]
#[derive(Clone, Copy)]
enum ExpectedSolutions {
    Zero,
    One,
    Multiple,
}

impl ExpectedSolutions {
    fn matches(self, count: usize) -> bool {
        match self {
            Self::Zero => count == 0,
            Self::One => count == 1,
            Self::Multiple => count >= 2,
        }
    }

    fn name(self) -> &'static str {
        match self {
            Self::Zero => "0",
            Self::One => "1",
            Self::Multiple => "2+",
        }
    }
}

struct Task {
    url: &'static str,
    expected: ExpectedSolutions,
}

// Example tasks (generated by https://semiexp.net/games/infinite_numberlink/index.html)
const EXAMPLE_TASKS: &[Task] = &[
    Task {
        url: "https://puzz.link/p?numlin/15/15/zg5do9-10n73h7l3h5jd4iaj-11q6hbz1k-10veap9ofm-11g6nfp8i1g2eh2ic4ici8gbw",
        expected: ExpectedSolutions::One,
    },
    Task {
        url: "https://puzz.link/p?numlin/14/14/uap6k2p8o7q9lbgam1y6h4j5p5k7h1u3gbg8k2g9u3k4u",
        expected: ExpectedSolutions::One,
    },
    Task {
        url: "https://puzz.link/p?numlin/15/15/z5g2h9l3o3rck1x9jch1h6kazual4gbi4j8ybi6l7g2m8n5h7z",
        expected: ExpectedSolutions::One,
    },
];

fn main() {
    let mut args = std::env::args();
    let program = args.next().unwrap_or_else(|| "example_tasks".to_string());
    let selected = match (args.next(), args.next()) {
        (None, None) => None,
        (Some(value), None) => match value.parse::<usize>() {
            Ok(0) | Err(_) => {
                eprintln!("usage: {program} [TASK_NUMBER]");
                std::process::exit(2);
            }
            Ok(number) => Some(number),
        },
        _ => {
            eprintln!("usage: {program} [TASK_NUMBER]");
            std::process::exit(2);
        }
    };

    if let Some(number) = selected {
        if number > EXAMPLE_TASKS.len() {
            eprintln!(
                "task number {number} is out of range (there are {} task(s))",
                EXAMPLE_TASKS.len()
            );
            std::process::exit(2);
        }
    }

    let mut failed = 0;

    for (index, task) in EXAMPLE_TASKS.iter().enumerate() {
        let task_number = index + 1;
        if selected.is_some_and(|number| number != task_number) {
            continue;
        }

        let started = Instant::now();
        let problem = decode_url(task.url);
        let answers = solver::solve(problem);
        let elapsed = started.elapsed();
        let count = answers.len();
        let matched = task.expected.matches(count);

        println!(
            "task {:>3}: {:>6.3?}, solutions={}, expected={}, {}",
            task_number,
            elapsed,
            count,
            task.expected.name(),
            if matched { "OK" } else { "FAIL" },
        );

        if !matched {
            failed += 1;
        }
    }

    let task_count = selected.map_or(EXAMPLE_TASKS.len(), |_| 1);
    println!("{} task(s), {} failure(s)", task_count, failed);

    if failed != 0 {
        std::process::exit(1);
    }
}
